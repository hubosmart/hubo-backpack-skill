"""Generate DRC rules for the minimum track width of power nets from the project config (SPEC-005 10.8), enforced by KiCad DRC.

The project config <board name>.hz_layout.json sits next to the board file, content copied from the design document (format: assets/hz_layout.example.json):
  power: [{"nets": [...], "current_a": current in A actually carried by the traces of this net, "layer": "outer"|"inner",
          "basis": "source of the current (design-document clause, part datasheet)", optional "copper_oz", "width_mm"}]
  checks: parameters of the high-speed / impedance / plane checks handed to prod_gate.py
The width is computed by this script per IPC-2221 (same formula as the KiCad calculator) for a 10 C temperature rise: outer layers default to 1 oz, inner layers 0.5 oz;
width_mm may only be wider than the computed value (margin), never narrower. For nets whose trunk is a pour and traces are only branches, fill current_a with the current the trace actually carries.
The generated rules go into a marked section at the end of <board name>.kicad_dru (rerunnable, only that section is replaced); when .kicad_dru does not exist or lacks
the base rules, the rules of assets/jlc_base.kicad_dru are first placed after (version 1) and before the project's own rules.
No net classes are written: MCP save_project flushes .kicad_pro back to defaults (item 7 of 07).

Usage (any python 3):
  python power_rules.py <board.kicad_pcb>            # generate / update
  python power_rules.py <board.kicad_pcb> --check    # check only, exit code 1 on mismatch (used by prod_gate)
"""
from __future__ import annotations

import argparse
import json
import math
import pathlib
import sys

BEGIN = "# >>> hz power rules (generated by power_rules.py from hz_layout.json; do not edit)"
END = "# <<< hz power rules"
BASE_BEGIN = "# >>> hz base rules (written by power_rules.py from assets/jlc_base.kicad_dru; do not edit)"
BASE_END = "# <<< hz base rules"
EXAMPLE_MARK = "[EXAMPLE VALUE - REPLACE]"
# legacy markers, kept for compatibility: written by earlier versions of this script / the project template into users' files.
# When rerun on an old project the old section is replaced whole, so two sections never coexist.
LEGACY_BEGINS = (
    "# >>> hz power rules（power_rules.py 按 hz_layout.json 生成，勿手改）",
    "# >>> hz power rules（power_rules.py 生成 / generated）",
)
LEGACY_BASE_BEGINS = (
    "# >>> hz base rules（power_rules.py 按 assets/jlc_base.kicad_dru 写入，勿手改）",
    "# >>> hz base rules（由 skill 的 power_rules.py 按 assets/jlc_base.kicad_dru 写入，勿手改 / generated, do not edit）",
)
LEGACY_EXAMPLE_MARKS = ("示例数值",)   # legacy marker, kept for compatibility
BASE = pathlib.Path(__file__).resolve().parents[1] / "assets" / "jlc_base.kicad_dru"
CHECKS = ("hs_review", "impedance_check", "plane_check", "fence_check", "route_check")


TEMP_RISE_C = 10                       # SPEC-005 10.8
BASE_MIN_MM = 0.127                    # SPEC-005 10.2 recommended track width, same as HZ_track_width in jlc_base.kicad_dru
DEFAULT_OZ = {"outer": 1.0, "inner": 0.5}
K = {"outer": 0.048, "inner": 0.024}   # IPC-2221: I = k*dT^0.44*A^0.725, A in mil^2


def ipc2221_width_mm(current_a, layer, copper_oz=None, temp_rise_c=TEMP_RISE_C):
    """Minimum track width required by IPC-2221 (mm). 1 oz = 1.378 mil (35 um). Pure function."""
    oz = copper_oz or DEFAULT_OZ[layer]
    area = (current_a / (K[layer] * temp_rise_c ** 0.44)) ** (1 / 0.725)
    return area / (1.378 * oz) * 0.0254


def required_width(e):
    """Final track width adopted for a config entry: the computed value rounded up to 0.001 mm, the larger of it, width_mm and the base minimum (width_mm kept as given).

    Never below the base minimum: power rules come after the template and override HZ_track_width, and a thin computed width for a low-current net would relax the minimum.
    """
    calc = ipc2221_width_mm(e["current_a"], e["layer"], e.get("copper_oz"))
    return max(math.ceil(calc * 1000 - 1e-9) / 1000, e.get("width_mm") or 0, BASE_MIN_MM), calc


def paths(board):
    b = pathlib.Path(board)
    return b.with_name(b.stem + ".hz_layout.json"), b.with_suffix(".kicad_dru")


def load_cfg(path):
    """Read and validate the project config; raise ValueError (saying which item) if invalid."""
    path = pathlib.Path(path)
    if not path.exists():
        raise ValueError(f"Project config {path.name} missing: create it from assets/hz_layout.example.json, content copied from the design document")
    cfg = json.loads(path.read_text(encoding="utf-8"))
    power = cfg.get("power")
    if not isinstance(power, list):
        raise ValueError("power must be a list (write [] and explain in the design document when the board really has no power nets to check)")
    for i, e in enumerate(power):
        nets = e.get("nets")
        if not nets or not isinstance(nets, list) or any(not isinstance(n, str) or not n or "'" in n for n in nets):
            raise ValueError(f"power[{i}].nets must be a non-empty list of net names (no single quotes)")
        if not isinstance(e.get("current_a"), (int, float)) or e["current_a"] <= 0:
            raise ValueError(f"power[{i}].current_a must be a positive number")
        if e.get("layer") not in K:
            raise ValueError(f"power[{i}].layer must be outer or inner (the layer the net's traces are on)")
        for k in ("copper_oz", "width_mm"):
            if k in e and (not isinstance(e[k], (int, float)) or e[k] <= 0):
                raise ValueError(f"power[{i}].{k} must be a positive number")
        calc = ipc2221_width_mm(e["current_a"], e["layer"], e.get("copper_oz"))
        if e.get("width_mm") and e["width_mm"] < calc:
            raise ValueError(f"power[{i}].width_mm {e['width_mm']} is below the IPC-2221 computed value {calc:.3f} mm")
        if not str(e.get("basis", "")).strip():
            raise ValueError(f"power[{i}].basis must state the source of the current (design-document clause, part datasheet)")
        if any(m in str(e["basis"]) for m in (EXAMPLE_MARK, *LEGACY_EXAMPLE_MARKS)):
            raise ValueError(f"power[{i}] is still an example value: replace it with the current from the design document")
    exc = cfg.get("netclass_exceptions", {})
    if not isinstance(exc, dict) or any(not isinstance(v, str) or not v.strip() for v in exc.values()):
        raise ValueError("netclass_exceptions must be {net class name: reason (who agreed, design-document clause)}")
    cfg["netclass_exceptions"] = exc
    checks = {k: v for k, v in cfg.get("checks", {}).items() if not k.startswith("_")}
    bad = [k for k in checks if k not in CHECKS]
    if bad:
        raise ValueError(f"checks only supports {', '.join(CHECKS)}, not recognized: {', '.join(bad)}")
    def _args_ok(v):
        return isinstance(v, list) and all(isinstance(x, str) for x in v)
    # Each entry is one parameter set (list of strings) or several (list of lists of strings: the same check run once per set, e.g. several impedance widths, several plane layers)
    if any(not (_args_ok(v) or (isinstance(v, list) and v and all(_args_ok(a) for a in v))) for v in checks.values()):
        raise ValueError("each entry of checks must be a list of string parameters, or a list of them (several parameter sets)")
    cfg["checks"] = checks
    return cfg


def render(power):
    """power config -> marked-section text (pure function)."""
    out = [BEGIN]
    for e in power:
        names = "_".join(e["nets"])
        cond = " || ".join(f"A.NetName == '{n}'" for n in e["nets"])
        basis = " ".join(str(e["basis"]).split())        # No line breaks inside a comment line
        width, calc = required_width(e)
        oz = e.get("copper_oz") or DEFAULT_OZ[e["layer"]]
        out += [f"# {', '.join(e['nets'])}: {e['current_a']:g} A ({basis}); IPC-2221 {e['layer']} {oz:g} oz, "
                f"temperature rise {TEMP_RISE_C} C, computed {calc:.3f} mm",
                f'(rule "HZ_PWR_{names}"',
                f'\t(condition "{cond}")',
                f"\t(constraint track_width (min {width:g}mm)))"]
    out.append(END)
    return "\n".join(out) + "\n"


def find_begin(text, begin, legacy):
    """Index of the earliest begin marker (current or legacy) in text; -1 if none (pure function)."""
    hits = [i for i in (text.find(m) for m in (begin, *legacy)) if i >= 0]
    return min(hits) if hits else -1


def has_base(text):
    """Whether text contains the base rule section, under the current or a legacy marker (pure function)."""
    return find_begin(text, BASE_BEGIN, LEGACY_BASE_BEGINS) >= 0


def ensure_base(text, base):
    """Write the base rule template into .kicad_dru, after (version 1) (pure function).

    The template section has begin/end markers and is replaced whole by the current template each time; after the template is revised, rerunning each project syncs it.
    Placed before the project's own rules: KiCad lets later rules override earlier ones, and local exceptions in the project (e.g. QFN breakout necking) must be able to override the template.
    """
    body = base.split("\n", 1)[1] if base.startswith("(version") else base
    block = BASE_BEGIN + "\n" + body.strip("\n") + "\n" + BASE_END + "\n"
    i, j = find_begin(text, BASE_BEGIN, LEGACY_BASE_BEGINS), text.find(BASE_END)
    if i >= 0 and j > i:
        return text[:i] + block + "\n" + text[j + len(BASE_END):].lstrip("\n")
    if not text.strip():
        return "(version 1)\n" + block + "\n"
    head, sep, rest = text.partition("\n")
    if not head.startswith("(version"):
        head, sep, rest = "(version 1)", "\n", text
    return head + sep + block + "\n" + rest.lstrip("\n")


def apply(text, block):
    """Write the marked section into the .kicad_dru text: replace the whole section if present, otherwise append at the end (pure function).

    Appending at the end is deliberate: KiCad lets later custom rules override earlier ones, and power rules must override the global minimum track width in the template.
    """
    i, j = find_begin(text, BEGIN, LEGACY_BEGINS), text.find(END)
    if i >= 0 and j > i:
        return text[:i] + block + text[j + len(END):].lstrip("\n")
    if not text.strip():
        text = "(version 1)\n"
    return text.rstrip("\n") + "\n\n" + block


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("board")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    cfg_path, dru = paths(a.board)
    try:
        cfg = load_cfg(cfg_path)
    except ValueError as e:
        raise SystemExit(f"{cfg_path.name}: {e}")
    text = dru.read_text(encoding="utf-8") if dru.exists() else ""
    want = apply(ensure_base(text, BASE.read_text(encoding="utf-8")), render(cfg["power"]))
    if a.check:
        ok = want == text
        print(f"{dru.name} base rules and power track-width rules {'match the config' if ok else 'do not match the config: rerun power_rules.py to regenerate'}")
        return 0 if ok else 1
    if not has_base(text):
        print(f"{dru.name}: added the {BASE.name} base rules")
    dru.write_text(want, encoding="utf-8", newline="\n")
    print(f"{dru.name}: wrote {len(cfg['power'])} power track-width rule(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
